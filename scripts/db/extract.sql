-- Extraction du schéma public de Takoras (LECTURE SEULE : uniquement des SELECT sur pg_catalog).
-- Renvoie une seule ligne, colonne "dump" = contenu de supabase/schema/baseline.sql (sans l'en-tête).
-- Voir scripts/db/README.md.
with
t as (
  select c.oid, c.relname, c.relowner, c.relacl, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p')
),
f as (
  select p.oid, p.proname, p.proowner, p.proacl, pg_get_function_identity_arguments(p.oid) as args
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
),
ext as (
  select string_agg(format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I; -- version %s',
           e.extname, n.nspname, e.extversion), E'\n' order by e.extname) s
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
),
seq as (
  select string_agg(format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s START %s INCREMENT %s MINVALUE %s MAXVALUE %s%s;',
           s.sequencename, s.data_type, s.start_value, s.increment_by, s.min_value, s.max_value,
           case when s.cycle then ' CYCLE' else '' end), E'\n' order by s.sequencename) s
  from pg_sequences s
  where s.schemaname = 'public'
    and not exists (select 1 from pg_depend d join pg_class sc on sc.oid = d.objid
                    where sc.relname = s.sequencename and d.deptype = 'i')  -- exclut les séquences d'IDENTITY
),
tbl as (
  select string_agg(format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
    (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
             when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end,
        case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
             when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
        case when a.attnotnull then ' NOT NULL' else '' end), E',\n' order by a.attnum)
     from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
     where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped)), E'\n\n' order by t.relname) s
  from t
),
seqown as (
  select string_agg(format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', sc.relname, tc.relname, a.attname),
           E'\n' order by sc.relname) s
  from pg_depend d
  join pg_class sc on sc.oid = d.objid and sc.relkind = 'S'
  join pg_class tc on tc.oid = d.refobjid
  join pg_namespace n on n.oid = tc.relnamespace and n.nspname = 'public'
  join pg_attribute a on a.attrelid = tc.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a'
),
con as (
  select string_agg(format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid)),
           E'\n' order by case co.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 when 'x' then 3 else 4 end, t.relname, co.conname) s
  from pg_constraint co join t on t.oid = co.conrelid
),
idx as (
  select string_agg(i.indexdef || ';', E'\n' order by i.tablename, i.indexname) s
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint co where co.conindid = format('public.%I', i.indexname)::regclass)
),
fun as (
  select string_agg('-- fonction : ' || f.proname || '(' || f.args || ')' || E'\n' || pg_get_functiondef(f.oid) || ';',
           E'\n\n' order by f.proname, f.args) s
  from f
),
trg as (
  select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by c.relname, tg.tgname) s
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not tg.tgisinternal
),
rls as (
  select string_agg(format('ALTER TABLE public.%I %s ROW LEVEL SECURITY;%s', relname,
           case when relrowsecurity then 'ENABLE' else 'DISABLE' end,
           case when relforcerowsecurity then format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', relname) else '' end),
           E'\n' order by relname) s
  from t
),
pol as (
  select string_agg(format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', policyname, tablename, permissive, cmd,
           array_to_string(roles, ', '),
           case when qual is not null then E'\n  USING (' || qual || ')' else '' end,
           case when with_check is not null then E'\n  WITH CHECK (' || with_check || ')' else '' end),
           E'\n\n' order by tablename, policyname) s
  from pg_policies where schemaname = 'public'
),
-- Droits : on part de l'ACL effective (acldefault si NULL) et on ne garde que les rôles exposés par Supabase.
tacl as (
  select t.relname, case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end as grantee,
         string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
  from t, aclexplode(coalesce(t.relacl, acldefault('r', t.relowner))) a
  left join pg_roles r on r.oid = a.grantee
  where a.grantee = 0 or r.rolname in ('anon','authenticated','service_role')
  group by 1, 2
),
tgr as (
  select string_agg(s, E'\n' order by relname, ord, s) s from (
    select relname, 0 as ord, format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated, service_role;', relname) as s from t
    union all
    select relname, 1, format('GRANT %s ON TABLE public.%I TO %s;', privs, relname, grantee) from tacl
  ) x
),
colgr as (
  select string_agg(format('GRANT %s (%I) ON TABLE public.%I TO %s;', a.privilege_type, att.attname, t.relname,
           case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), E'\n' order by t.relname, att.attname) s
  from t join pg_attribute att on att.attrelid = t.oid and att.attnum > 0 and att.attacl is not null
  cross join aclexplode(att.attacl) a
  left join pg_roles r on r.oid = a.grantee
),
facl as (
  select f.proname, f.args, case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end as grantee
  from f, aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) a
  left join pg_roles r on r.oid = a.grantee
  where a.privilege_type = 'EXECUTE' and (a.grantee = 0 or r.rolname in ('anon','authenticated','service_role'))
),
fgr as (
  select string_agg(s, E'\n' order by proname, args, ord) s from (
    select proname, args, 0 as ord, format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated, service_role;', proname, args) as s from f
    union all
    select proname, args, 1, format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', proname, args, string_agg(grantee, ', ' order by grantee))
    from facl group by proname, args
  ) x
),
rt as (
  select string_agg(format('ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;', schemaname, tablename), E'\n' order by tablename) s
  from pg_publication_tables where pubname = 'supabase_realtime'
),
cnt as (
  select format('-- Comptes : %s fonctions (%s SECURITY DEFINER), %s tables, %s policies, %s triggers, %s index hors contraintes, %s tables realtime',
    (select count(*) from f),
    (select count(*) from pg_proc p where p.oid in (select oid from f) and p.prosecdef),
    (select count(*) from t),
    (select count(*) from pg_policies where schemaname = 'public'),
    (select count(*) from pg_trigger tg where tg.tgrelid in (select oid from t) and not tg.tgisinternal),
    (select count(*) from pg_indexes i where i.schemaname = 'public'
       and not exists (select 1 from pg_constraint co where co.conindid = format('public.%I', i.indexname)::regclass)),
    (select count(*) from pg_publication_tables where pubname = 'supabase_realtime')) s
)
select concat_ws(E'\n\n',
  cnt.s,
  E'-- =====================================================================\n-- 1. EXTENSIONS\n-- =====================================================================', ext.s,
  E'-- =====================================================================\n-- 2. TABLES (séquences, colonnes, défauts, contraintes)\n-- =====================================================================',
  coalesce(seq.s, '-- (aucune séquence autonome)'), tbl.s, coalesce(seqown.s, '-- (aucune séquence possédée)'), con.s,
  E'-- =====================================================================\n-- 3. INDEX (hors index portés par une contrainte)\n-- =====================================================================', coalesce(idx.s, '-- (aucun)'),
  E'-- =====================================================================\n-- 4. FONCTIONS (schéma public)\n-- =====================================================================', fun.s,
  E'-- =====================================================================\n-- 5. TRIGGERS\n-- =====================================================================', coalesce(trg.s, '-- (aucun trigger sur le schéma public)'),
  E'-- =====================================================================\n-- 6. RLS (activation par table)\n-- =====================================================================', rls.s,
  E'-- =====================================================================\n-- 7. POLICIES\n-- =====================================================================', coalesce(pol.s, '-- (aucune)'),
  E'-- =====================================================================\n-- 8. DROITS (tables, colonnes, fonctions) pour PUBLIC / anon / authenticated / service_role\n-- =====================================================================',
  tgr.s, coalesce(colgr.s, '-- (aucun droit par colonne)'), fgr.s,
  E'-- =====================================================================\n-- 9. REALTIME (publication supabase_realtime)\n-- =====================================================================', coalesce(rt.s, '-- (aucune table)'),
  E'-- =====================================================================\n-- 10. CRON\n-- =====================================================================',
  case when to_regclass('cron.job') is null then '-- pg_cron n''est pas installé : aucune tâche planifiée.'
       else '-- pg_cron présent : exporter cron.job (voir README)' end
) as dump
from cnt, ext, seq, tbl, seqown, con, idx, fun, trg, rls, pol, tgr, colgr, fgr, rt;
